export function getServicio(slug) {
  return SERVICIOS.find((servicio) => servicio.slug === slug)
}

// citaId pedido en /citas?servicio=<citaId>; cadena vacía si falta o no existe.
export function servicioDesdeQuery(search) {
  const pedido = new URLSearchParams(search).get('servicio')
  return SERVICIOS.some((servicio) => servicio.citaId === pedido) ? pedido : ''
}
